const MyResellersTable = () => {
    const { user, isLoading: isUserLoading } = useUser();
    const firestore = useFirestore();
    const [resellerStats, setResellerStats] = useState<any[]>([]);
    const [isLoading, setIsLoading] = useState(true);
    const [selectedReseller, setSelectedReseller] = useState<any | null>(null);
    const [isSalesDialogOpen, setIsSalesDialogOpen] = useState(false);

    useEffect(() => {
        if (!user || !firestore) {
            if (!isUserLoading) setIsLoading(false);
            return;
        }

        const fetchData = async () => {
            setIsLoading(true);
            try {
                // 1. Find all approved reseller applications for the current seller
                const appsQuery = query(collection(firestore, 'resellerApplications'), where('sellerId', '==', user.uid), where('status', '==', 'approved'));
                const appsSnapshot = await getDocs(appsQuery);
                const resellerIds = appsSnapshot.docs.map(d => (d.data() as ResellerApplication).resellerId);

                if (resellerIds.length === 0) {
                    setResellerStats([]);
                    setIsLoading(false);
                    return;
                }

                // 2. Fetch profiles for these resellers
                // Firestore 'in' query is limited to 30 items. For larger scale, this would need batching.
                const resellersQuery = query(collection(firestore, 'userProfiles'), where('id', 'in', resellerIds.slice(0, 30)));
                const resellersSnapshot = await getDocs(resellersQuery);
                const resellersMap = new Map(resellersSnapshot.docs.map(d => [d.id, d.data() as UserProfile]));

                // 3. Fetch all orders made by these resellers for the current seller
                const ordersQuery = query(collection(firestore, 'orders'), where('sellerId', '==', user.uid), where('resellerId', 'in', resellerIds.slice(0, 30)));
                const ordersSnapshot = await getDocs(ordersQuery);
                const orders = ordersSnapshot.docs.map(d => d.data() as Order);

                // 4. Aggregate stats for each reseller
                const stats = Array.from(resellersMap.values()).map(resellerProfile => {
                    const resellerOrders = orders.filter(o => o.resellerId === resellerProfile.id);
                    const totalSales = resellerOrders.length;
                    const totalEarnings = resellerOrders.reduce((sum, order) => sum + (order.resellerCommission || 0), 0);

                    return {
                        id: resellerProfile.id,
                        fullName: resellerProfile?.fullName || 'Unknown Reseller',
                        profilePictureUrl: resellerProfile?.profilePictureUrl,
                        salesCount: totalSales,
                        totalEarnings: totalEarnings,
                        status: 'Active',
                        orders: resellerOrders,
                    };
                }).sort((a,b) => b.totalEarnings - a.totalEarnings);
                
                setResellerStats(stats);
            } catch (error) {
                console.error("Error fetching reseller data:", error);
            } finally {
                setIsLoading(false);
            }
        };

        fetchData();
    }, [user, firestore, isUserLoading]);
    

    const handleViewSales = (reseller: any) => {
        setSelectedReseller(reseller);
        setIsSalesDialogOpen(true);
    };

    if (isLoading) {
        return (
             <Table>
                <TableHeader>
                    <TableRow>
                        <TableHead>Reseller</TableHead>
                        <TableHead className="text-center">Sales</TableHead>
                        <TableHead className="text-right">Commission Paid (USD)</TableHead>
                        <TableHead className="text-center">Status</TableHead>
                        <TableHead className="text-right">Actions</TableHead>
                    </TableRow>
                </TableHeader>
                <TableBody>
                    {[...Array(3)].map((_, i) => (
                        <TableRow key={i}>
                            <TableCell><Skeleton className="h-10 w-40" /></TableCell>
                            <TableCell><Skeleton className="h-6 w-10 mx-auto" /></TableCell>
                            <TableCell><Skeleton className="h-6 w-20 ml-auto" /></TableCell>
                            <TableCell><Skeleton className="h-6 w-16 mx-auto" /></TableCell>
                            <TableCell><Skeleton className="h-8 w-24 ml-auto" /></TableCell>
                        </TableRow>
                    ))}
                </TableBody>
            </Table>
        )
    }

    return (
        <>
            <Table>
                <TableHeader>
                    <TableRow>
                        <TableHead>Reseller</TableHead>
                        <TableHead className="text-center">Sales</TableHead>
                        <TableHead className="text-right">Commission Paid (USD)</TableHead>
                        <TableHead className="text-center">Status</TableHead>
                        <TableHead className="text-right">Actions</TableHead>
                    </TableRow>
                </TableHeader>
                <TableBody>
                    {resellerStats.length > 0 ? (
                        resellerStats.map(reseller => (
                            <TableRow key={reseller.id}>
                                <TableCell className="font-medium flex items-center gap-2">
                                    <Avatar className="h-8 w-8">
                                        <AvatarImage src={reseller.profilePictureUrl || `https://picsum.photos/seed/${reseller.id}/40`} />
                                        <AvatarFallback>{reseller.fullName?.charAt(0)}</AvatarFallback>
                                    </Avatar>
                                    {reseller.fullName}
                                </TableCell>
                                <TableCell className="text-center">{reseller.salesCount}</TableCell>
                                <TableCell className="text-right">${reseller.totalEarnings.toFixed(2)}</TableCell>
                                <TableCell className="text-center">
                                    <Badge variant="default" className="bg-green-600/80">{reseller.status}</Badge>
                                </TableCell>
                                <TableCell className="text-right">
                                    <Button variant="outline" size="sm" onClick={() => handleViewSales(reseller)}>View Sales</Button>
                                </TableCell>
                            </TableRow>
                        ))
                    ) : (
                        <TableRow>
                            <TableCell colSpan={5} className="h-24 text-center">You have no approved resellers yet, or they haven't made any sales.</TableCell>
                        </TableRow>
                    )}
                </TableBody>
            </Table>
            <ResellerSalesDialog 
                reseller={selectedReseller}
                sales={selectedReseller?.orders || []}
                isOpen={isSalesDialogOpen}
                onOpenChange={setIsSalesDialogOpen}
            />
        </>
    );
};


export default function ResellerCenterPage() {
    const { user } = useUser();
    const firestore = useFirestore();
    const [stats, setStats] = useState({ totalResellers: 0, totalSales: 0, totalCommissionPaid: 0 });
    const [isLoadingStats, setIsLoadingStats] = useState(true);

    useEffect(() => {
        if (!user || !firestore) return;
        setIsLoadingStats(true);
        const fetchData = async () => {
            try {
                const appsQuery = query(collection(firestore, 'resellerApplications'), where('sellerId', '==', user.uid), where('status', '==', 'approved'));
                const appsSnapshot = await getDocs(appsQuery);
                const totalResellers = appsSnapshot.size;

                const resellerIds = appsSnapshot.docs.map(d => (d.data() as ResellerApplication).resellerId);
                if (resellerIds.length > 0) {
                     const ordersQuery = query(collection(firestore, 'orders'), where('sellerId', '==', user.uid), where('resellerId', 'in', resellerIds.slice(0,30)));
                    const ordersSnapshot = await getDocs(ordersQuery);
                    const totalSales = ordersSnapshot.size;
                    const totalCommissionPaid = ordersSnapshot.docs.reduce((acc, doc) => acc + (doc.data().resellerCommission || 0), 0);
                    setStats({ totalResellers, totalSales, totalCommissionPaid });
                } else {
                    setStats({ totalResellers: 0, totalSales: 0, totalCommissionPaid: 0 });
                }
            } catch (error) {
                console.error("Error fetching stats:", error);
            } finally {
                setIsLoadingStats(false);
            }
        };
        fetchData();
    }, [user, firestore]);

    return (
        <SellerLayout>
        <div className="flex-1 space-y-4 p-8 pt-6">
            <h1 className="font-headline text-3xl font-bold tracking-tight">
            Reseller Center
            </h1>
            
            <Tabs defaultValue="analytics" className="space-y-4">
                <TabsList>
                    <TabsTrigger value="analytics">Analytics</TabsTrigger>
                    <TabsTrigger value="commissions">Commission Rules</TabsTrigger>
                </TabsList>

                <TabsContent value="analytics" className="space-y-6">
                    <div className="grid gap-4 md:grid-cols-3">
                        <StatCard isLoading={isLoadingStats} title="Total Resellers" value={stats.totalResellers.toString()} icon={Users} />
                        <StatCard isLoading={isLoadingStats} title="Total Reseller Sales" value={stats.totalSales.toString()} icon={ShoppingBag} />
                        <StatCard isLoading={isLoadingStats} title="Total Commission Paid" value={`$${stats.totalCommissionPaid.toLocaleString()}`} icon={CircleDollarSign} />
                    </div>

                    <Card>
                        <CardHeader>
                            <CardTitle>My Resellers</CardTitle>
                            <CardDescription>Manage and view the performance of your resellers.</CardDescription>
                        </CardHeader>
                        <CardContent>
                           <MyResellersTable />
                        </CardContent>
                    </Card>

                    <Card>
                        <CardHeader>
                            <CardTitle>Top Shared Products</CardTitle>
                            <CardDescription>Your products being shared most frequently by the reseller network.</CardDescription>
                        </CardHeader>
                        <CardContent>
                           <SellerTopSharedProductsTable />
                        </CardContent>
                    </Card>
                </TabsContent>

                <TabsContent value="commissions" className="space-y-4">
                    <Card>
                    <CardHeader>
                        <CardTitle className="flex items-center gap-2">
                        <BadgePercent />
                        Set Product Commission Rates
                        </CardTitle>
                        <CardDescription>Set the percentage a reseller will earn for selling each product. A rate of 0% means the product is not available for reselling.</CardDescription>
                    </CardHeader>
                    <CardContent>
                        <CommissionSettingsTable />
                    </CardContent>
                    </Card>
                </TabsContent>
            </Tabs>
        </div>
        </SellerLayout>
    );
}
