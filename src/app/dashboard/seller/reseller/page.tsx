const ResellerSalesDialog = ({ reseller, sellerId, isOpen, onOpenChange }: { reseller: UserProfile | null, sellerId: string, isOpen: boolean, onOpenChange: (open: boolean) => void }) => {
    const firestore = useFirestore();

    const salesQuery = useMemoFirebase(() => {
        if (!reseller) return null;
        return query(
            collection(firestore, 'orders'),
            where('sellerId', '==', sellerId),
            where('resellerId', '==', reseller.id),
            where('orderStatus', 'in', ['delivered', 'shipped', 'processing'])
        );
    }, [firestore, reseller, sellerId]);

    const { data: sales, isLoading } = useCollection<Order>(salesQuery);

    return (
        <Dialog open={isOpen} onOpenChange={onOpenChange}>
            <DialogContent className="max-w-2xl">
                <DialogHeader>
                    <DialogTitle>Sales by {reseller?.fullName}</DialogTitle>
                    <DialogDescription>A detailed list of all sales generated by this reseller for your shop.</DialogDescription>
                </DialogHeader>
                <div className="max-h-[60vh] overflow-y-auto">
                    <Table>
                        <TableHeader>
                            <TableRow>
                                <TableHead>Product</TableHead>
                                <TableHead className="text-right">Commission</TableHead>
                                <TableHead className="text-center">Status</TableHead>
                            </TableRow>
                        </TableHeader>
                        <TableBody>
                            {isLoading && <TableRow><TableCell colSpan={3} className="text-center">Loading sales...</TableCell></TableRow>}
                            {!isLoading && sales && sales.length > 0 ? (
                                sales.map(sale => (
                                    <TableRow key={sale.id}>
                                        <TableCell>
                                            <div className="flex items-center gap-3">
                                                <Image src={sale.productImage || ''} alt={sale.productName || 'product'} width={40} height={40} className="rounded-md object-cover" />
                                                <span className="font-medium">{sale.productName}</span>
                                            </div>
                                        </TableCell>
                                        <TableCell className="text-right font-semibold text-primary">${(sale.resellerCommission || 0).toFixed(2)}</TableCell>
                                        <TableCell className="text-center"><Badge variant="secondary" className="capitalize">{sale.orderStatus}</Badge></TableCell>
                                    </TableRow>
                                ))
                            ) : !isLoading && (
                                <TableRow>
                                    <TableCell colSpan={3} className="text-center h-24">No sales recorded for this reseller yet.</TableCell>
                                </TableRow>
                            )}
                        </TableBody>
                    </Table>
                </div>
            </DialogContent>
        </Dialog>
    );
};


const MyResellersTable = ({ sellerId }: { sellerId: string }) => {
    const firestore = useFirestore();
    const [selectedReseller, setSelectedReseller] = useState<UserProfile | null>(null);
    const [isSalesDialogOpen, setIsSalesDialogOpen] = useState(false);

    // 1. Get all orders for the current seller that have a reseller
    const resellerOrdersQuery = useMemoFirebase(() => {
        return query(collection(firestore, 'orders'), where('sellerId', '==', sellerId), where('resellerId', '!=', null));
    }, [firestore, sellerId]);
    const { data: resellerOrders, isLoading: areOrdersLoading } = useCollection<Order>(resellerOrdersQuery);

    // 2. Get all unique reseller IDs from those orders
    const resellerIds = useMemo(() => {
        if (!resellerOrders) return [];
        return [...new Set(resellerOrders.map(o => o.resellerId).filter(Boolean) as string[])];
    }, [resellerOrders]);

    // 3. Fetch the profiles of those resellers
    const resellersQuery = useMemoFirebase(() => {
        if (resellerIds.length === 0) return null;
        return query(collection(firestore, 'userProfiles'), where('id', 'in', resellerIds));
    }, [firestore, resellerIds]);
    const { data: resellers, isLoading: areResellersLoading } = useCollection<UserProfile>(resellersQuery);

    // 4. Combine data for the table
    const tableData = useMemo(() => {
        if (!resellers || !resellerOrders) return [];
        return resellers.map(reseller => {
            const sales = resellerOrders.filter(o => o.resellerId === reseller.id);
            const earnings = sales.reduce((acc, o) => acc + (o.resellerCommission || 0), 0);
            return {
                ...reseller,
                salesCount: sales.length,
                totalEarnings: earnings,
            };
        });
    }, [resellers, resellerOrders]);
    
    const isLoading = areOrdersLoading || areResellersLoading;

    const handleViewSales = (reseller: UserProfile) => {
        setSelectedReseller(reseller);
        setIsSalesDialogOpen(true);
    };

    if (isLoading) {
        return <p>Loading reseller data...</p>;
    }

    return (
        <>
            <Table>
                <TableHeader>
                    <TableRow>
                        <TableHead>Reseller</TableHead>
                        <TableHead className="text-center">Sales</TableHead>
                        <TableHead className="text-right">Your Earnings (USD)</TableHead>
                        <TableHead className="text-center">Status</TableHead>
                        <TableHead className="text-right">Actions</TableHead>
                    </TableRow>
                </TableHeader>
                <TableBody>
                    {tableData.length > 0 ? (
                        tableData.map(reseller => (
                            <TableRow key={reseller.id}>
                                <TableCell className="font-medium flex items-center gap-2">
                                    <Avatar className="h-8 w-8">
                                        <AvatarImage src={reseller.profilePictureUrl || `https://picsum.photos/seed/${reseller.id}/40`} />
                                        <AvatarFallback>{reseller.fullName?.charAt(0)}</AvatarFallback>
                                    </Avatar>
                                    {reseller.fullName}
                                </TableCell>
                                <TableCell className="text-center">{reseller.salesCount}</TableCell>
                                <TableCell className="text-right">${reseller.totalEarnings.toFixed(2)}</TableCell>
                                <TableCell className="text-center">
                                    <Badge variant="default" className="bg-green-600/80">Active</Badge>
                                </TableCell>
                                <TableCell className="text-right">
                                    <Button variant="outline" size="sm" onClick={() => handleViewSales(reseller)}>View Sales</Button>
                                </TableCell>
                            </TableRow>
                        ))
                    ) : (
                        <TableRow>
                            <TableCell colSpan={5} className="h-24 text-center">No resellers have made sales for you yet.</TableCell>
                        </TableRow>
                    )}
                </TableBody>
            </Table>
            <ResellerSalesDialog 
                reseller={selectedReseller}
                sellerId={sellerId}
                isOpen={isSalesDialogOpen}
                onOpenChange={setIsSalesDialogOpen}
            />
        </>
    );
};


