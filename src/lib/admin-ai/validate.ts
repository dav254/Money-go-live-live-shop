/**
 * ADMIN AI — shared vocabulary and pure guards.
 *
 * Everything here is deliberately free of I/O so the rules the Command Centre
 * promises can be tested without a network, a database or an Ollama install:
 *
 *   • text limits and control-character stripping,
 *   • status names that include UNKNOWN (a check that never ran is not green),
 *   • report shapes that can never claim an action was executed,
 *   • one error formatter that keeps upstream URLs and secrets out of replies.
 */

export const MAX_MESSAGE_CHARS = 8_000;
export const MAX_INSTRUCTION_CHARS = 24_000;
export const MAX_TITLE_CHARS = 120;
export const MAX_MODEL_CHARS = 80;

/** What a probe can honestly report. `unknown` means "not measured". */
export const CHECK_STATES = ['online', 'degraded', 'offline', 'unknown'] as const;
export type CheckState = (typeof CHECK_STATES)[number];

export function isCheckState(value: unknown): value is CheckState {
  return typeof value === 'string' && (CHECK_STATES as readonly string[]).includes(value);
}

export const MESSAGE_ROLES = ['user', 'assistant', 'system'] as const;
export type MessageRole = (typeof MESSAGE_ROLES)[number];

export const REPORT_STATUSES = ['completed', 'failed', 'running'] as const;
export type ReportStatus = (typeof REPORT_STATUSES)[number];

export function cleanText(value: unknown, max: number): string {
  return String(value ?? '')
    .replace(/[\u0000-\u0008\u000B\u000C\u000E-\u001F\u007F]/g, '')
    .replace(/\r\n/g, '\n')
    .trim()
    .slice(0, max);
}

/** Single-line text (titles) collapses newlines instead of keeping them. */
export function cleanLine(value: unknown, max: number): string {
  return cleanText(value, max).replace(/\s+/g, ' ').trim();
}

export function isSafeModelName(value: unknown): value is string {
  return typeof value === 'string' && /^[A-Za-z0-9][A-Za-z0-9._:/-]{0,80}$/.test(value);
}

/**
 * A missing configuration is NOT an outage, and an unreachable service is not
 * "unknown". This keeps those three apart in one place.
 */
export function stateFromProbe(input: {
  configured: boolean;
  reachable: boolean;
  degraded?: boolean;
}): CheckState {
  if (!input.configured) return 'unknown';
  if (!input.reachable) return 'offline';
  return input.degraded ? 'degraded' : 'online';
}

/**
 * Turns any thrown value into one sentence a person can act on.
 *
 * Upstream hosts, tokens and stack traces are intentionally dropped: an error
 * screen is not a place to publish the VPS topology. The caller logs the raw
 * error server-side if it needs it.
 */
export function publicError(error: unknown): string {
  const candidate = error as { name?: string; code?: string; message?: string };
  const code = String(candidate?.code ?? '');
  const message = String(candidate?.message ?? '');

  if (candidate?.name === 'AbortError' || code === 'timeout' || /timed? ?out/i.test(message)) {
    return 'The AI service did not answer in time. Try again, or check that the model is loaded.';
  }
  if (code === 'ECONNREFUSED' || /ECONNREFUSED/i.test(message)) {
    return 'The AI service refused the connection on the server. It may not be running.';
  }
  if (code === 'ENOTFOUND' || code === 'EAI_AGAIN' || /ENOTFOUND|EAI_AGAIN/i.test(message)) {
    return 'The server could not resolve the AI service address.';
  }
  if (code === 'not_configured') {
    return 'The AI service is not configured on this server.';
  }
  if (code === 'unauthorized') {
    return 'The AI service rejected the server credentials. Check the service password on the VPS.';
  }
  if (code === 'rejected') {
    return 'The AI service rejected the request. Check its server log before retrying.';
  }
  if (code === 'bad_response') {
    return 'The AI service answered, but not in a shape Vidnov can read.';
  }
  if (code === 'empty_response') {
    return 'The model returned an empty answer. Try rephrasing the request.';
  }
  if (code === 'pocketbase_unavailable') {
    return 'Saved history is unavailable — the local store could not be reached. The answer itself is unaffected.';
  }
  return 'The request could not be completed. Try again.';
}

/**
 * THE EXECUTION GUARANTEE, ENCODED.
 *
 * Every report the Command Centre creates states that nothing was run. This is
 * not a UI label that could drift — the server writes it, and a report can only
 * be built through this function.
 */
export const NOT_EXECUTED_NOTE =
  'Generated by the model. No files, databases, services or repositories were read or modified by this task.';

export interface ReportDraftInput {
  id: string;
  title: string;
  instruction: string;
  model: string;
  status: ReportStatus;
  result: string;
  error?: string | null;
  startedAt: string;
  completedAt: string | null;
  latencyMs?: number | null;
}

export interface ReportDraft {
  id: string;
  title: string;
  instruction: string;
  model: string;
  status: ReportStatus;
  result: string;
  error: string | null;
  /** Always false in Phase 1: the backend has no execution path. */
  executed: false;
  /** True when the text only proposes work. */
  proposedOnly: true;
  filesInspected: string[];
  filesChanged: string[];
  verification: string;
  nextStep: string | null;
  startedAt: string;
  completedAt: string | null;
  latencyMs: number | null;
  note: string;
}

/**
 * Builds the stored report. Pure, so the "never claim execution" rule is a
 * tested property rather than a comment.
 */
export function buildReport(input: ReportDraftInput): ReportDraft {
  return {
    id: cleanText(input.id, 120),
    title: cleanLine(input.title, MAX_TITLE_CHARS) || 'Untitled instruction',
    instruction: cleanText(input.instruction, MAX_INSTRUCTION_CHARS),
    model: isSafeModelName(input.model) ? input.model : 'unknown',
    status: input.status,
    result: cleanText(input.result, 60_000),
    error: input.error ? cleanText(input.error, 2_000) : null,
    executed: false,
    proposedOnly: true,
    // The model has no repository access, so these are empty by construction.
    filesInspected: [],
    filesChanged: [],
    verification: 'Not run — this task generated a report only. Nothing was executed, so there is nothing to verify yet.',
    nextStep: extractNextStep(input.result),
    startedAt: input.startedAt,
    completedAt: input.completedAt,
    latencyMs: typeof input.latencyMs === 'number' ? input.latencyMs : null,
    note: NOT_EXECUTED_NOTE,
  };
}

/**
 * The model often ends with "Next step: …". We keep it only when it is clearly
 * labelled; guessing would turn a suggestion into a fabricated plan.
 */
export function extractNextStep(text: string): string | null {
  const match = /^\s*(?:next step|recommended next step|next action)\s*[:\-]\s*(.+)$/im.exec(text);
  const value = match?.[1]?.trim();
  return value ? value.slice(0, 500) : null;
}

/** Conversation titles come from the first message, never from the model. */
export function titleFromMessage(message: string): string {
  const full = cleanLine(message, 4_000);
  if (!full) return 'New conversation';
  const limit = MAX_TITLE_CHARS - 1;
  return full.length > limit ? `${full.slice(0, limit)}…` : full;
}
